// bcdice の StaticLoader は i18n JSON を変数入りの require で読むため、rolldown の CJS 変換が
// 効かない development ビルドではブラウザで require が露出して落ちる。
// ここで i18n_list.json から静的 import の一覧を生成し、アプリ側で読み込めるようにする。
import { existsSync, readFileSync, writeFileSync } from 'fs';

const I18N_LIST_PATH = 'node_modules/bcdice/lib/bcdice/i18n_list.json';
const I18N_DIR = 'node_modules/bcdice/lib/bcdice/i18n';
const OUTPUT_PATH = 'src/app/domain/dice/bcdice/bcdice-i18n.generated.ts';

const { i18nList } = JSON.parse(readFileSync(I18N_LIST_PATH, 'utf-8'));

const entries = [];
for (const { baseClassName, locales } of i18nList) {
  for (const locale of locales) {
    const fileName = `${baseClassName}.${locale}.json`;
    if (!existsSync(`${I18N_DIR}/${fileName}`)) {
      console.warn(`[generate-bcdice-i18n] 見つかりません: ${fileName}`);
      continue;
    }
    entries.push({ identifier: `${baseClassName}_${locale}`, fileName });
  }
}

entries.sort((a, b) => (a.fileName < b.fileName ? -1 : a.fileName > b.fileName ? 1 : 0));

const imports = entries
  .map(({ identifier, fileName }) => `import ${identifier} from 'bcdice/lib/bcdice/i18n/${fileName}';`)
  .join('\n');

const list = entries.map(({ identifier }) => `  ${identifier},`).join('\n');

const source = `// generated by scripts/generate-bcdice-i18n.mjs — do not edit
${imports}

export const BCDICE_I18N_TRANSLATIONS: readonly object[] = [
${list}
];
`;

writeFileSync(OUTPUT_PATH, source);
console.log(`[generate-bcdice-i18n] ${entries.length} 件を ${OUTPUT_PATH} に出力しました`);
